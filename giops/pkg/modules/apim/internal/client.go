// Package internal holds what the APIM-client modules share.
package internal

import (
	"context"

	apimsdk "github.com/gravitee-io/gravitee-automation-sdk/apim-sdk/pkg/sdk"
	"github.com/gravitee-io/gravitee-automation-sdk/giops/pkg/core"
)

// Client returns the APIM client of the module command running in ctx.
func Client(ctx context.Context) *apimsdk.APIMClient {
	return core.Client[apimsdk.APIMClient](ctx)
}
